# USD per 1,000,000 tokens, (input, output). Source: claude-api model table.
PRICING = {
    "sonnet": (3.00, 15.00),
    "opus": (5.00, 25.00),
    "haiku": (1.00, 5.00),
}
# Measured, not assumed. The previous constants (3.5 chars/token, 3000 output
# tokens, no per-call overhead) under-estimated a real run by ~3x on input and
# ~9x on output, which breaks the one promise this file makes - that the figure
# printed before a metered run is never lower than the spend that follows.
#
# Fitted against three assembles on claude-sonnet-5 (2026-07-31): prompts of
# 120,941 / 132,009 / 60,500 chars reported 80,946 / 84,221 / 57,682 input
# tokens. Two unknowns, three points: solving the extremes gives a fixed
# per-call overhead plus a density, and the held-out middle point predicts to
# +1.2%. The fixed term is the CLI's own system prompt, which is charged on
# every call however small the brief - the reason a per-char-only estimate is
# hopeless for short items.
# Single-sourced in assembler.py so the batch pre-flight and the single-run gate
# cannot quote different numbers for the same work. (Observed output: 7,829 /
# 25,728 / 31,023 - the model re-emits every reference block into the front
# matter, so output tracks reference count, not prose length. Ceiling by design.)
CHARS_PER_TOKEN = asm.CHARS_PER_TOKEN
FIXED_INPUT_TOKENS = asm.FIXED_INPUT_TOKENS
EST_OUTPUT_TOKENS = asm.EST_OUTPUT_TOKENS
EST_OUTPUT_TOKENS_RECORD = asm.EST_OUTPUT_TOKENS_RECORD


def _read_items(args, kind: str) -> list[str]:
    """Gather the work list for `kind` ('nodes' | 'records') from the positional
    list or the corresponding --<kind>-file (one item per line, # comments ok)."""
    items: list[str] = list(getattr(args, kind) or [])
    fpath = getattr(args, f"{kind[:-1]}s_file", None) or getattr(
        args, f"{kind}_file", None
    )
    if fpath:
        for line in Path(fpath).read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                items.append(line)
    return items


def _target_path(args, kind: str, item: str) -> Path | None:
    """Where this item would be written, resolved without generating anything."""
    node = _resolve_node(args, kind, item)
    if node is None:
        return None
    section = asm.SECTION_BY_TYPE.get(node["type"], node["type"] + "s")
    return asm.output_path(Path(args.content_root), section, asm.node_slug(node))


def _check_suspect_names(args, kind: str, items: list[str]) -> dict[str, str]:
    """Items whose NAME says the node is not a real entity, mapped to the reason.

    Refused in the pre-flight for the same reason as a slug collision: the failure
    is invisible afterwards. A corrupted merge assembles into a fluent, heavily
    cited article about a person who does not exist, and nothing downstream - not
    the citation check, not the link resolver, not a human skim - flags it.
    """
    suspect: dict[str, str] = {}
    for item in items:
        node = _resolve_node(args, kind, item)
        if node is None:
            continue
        reason = asm.suspect_entity_name(node.get("name"), node.get("type"))
        if reason:
            suspect[item] = f'"{node.get("name")}" - {reason}'
    return suspect


def _check_slug_collisions(args, kind: str, items: list[str]) -> dict[str, list[str]]:
    """Items in this run that would write to the SAME file.

    Two live nodes can compete for one URL - the graph currently has five such
    pairs, including one at 144 claims against 5. Assembling both writes the same
    path twice and the second silently wins, so the page is decided by list order
    and the loss is invisible. Caught here rather than at write time because a
    pre-flight costs nothing and a discovered overwrite costs a whole article.
    """
    seen: dict[str, list[str]] = {}
    for item in items:
        path = _target_path(args, kind, item)
        if path is not None:
            seen.setdefault(str(path), []).append(item)
    return {p: its for p, its in seen.items() if len(its) > 1}


def _load(args, kind: str, item: str):
    """(node, claims, related) for one item, read-only, or None if unresolvable.
    The single place a work item is turned into the assembler's inputs, so the
    pre-flight and the estimate cannot disagree about what an item resolves to."""
    if kind == "nodes":
        import sqlite3

        conn = sqlite3.connect(args.db)
        node = asm.load_node(conn, item)
        if not node:
            return None
        return (
            node,
            asm.claims_for_node(conn, node["id"]),
            asm.related_nodes(conn, node["id"]),
        )
    if kind == "briefs":
        loaded = asm.load_brief(Path(args.briefs_root), item)
        if not loaded:
            return None
        brief, _slug = loaded
        return (
            asm.brief_node(brief),
            asm.claims_from_brief(brief),
            asm.related_from_brief(brief),
        )
    loaded = asm.load_digest(Path(args.digests_root), item)
    if not loaded:
        return None
    digest, friendly_name = loaded
    return (
        asm.record_node(digest, friendly_name),
        asm.claims_from_digest(digest),
        asm.related_from_digest(digest),
    )


def _resolve_node(args, kind: str, item: str) -> dict | None:
    loaded = _load(args, kind, item)
    return loaded[0] if loaded else None


def _prompt_chars(args, kind: str, item: str) -> int | None:
    """Build the assembly prompt for one item read-only (no API) and return its
    character count, or None if the item can't be resolved."""
    loaded = _load(args, kind, item)
    if loaded is None:
        return None
    node, claims, related = loaded
    return len(asm.build_prompt(node, claims, related))


def openrouter_budget_remaining() -> tuple[float, float] | None:
    """(spent_today, daily_limit) from OpenRouter, or None if unreadable.

    The daily budget is a SHARED workspace pool - this component, the digester's
    benchmarks and anything else on OpenRouter draw the same $3 - and no consumer
    can see the others' spend when sizing work. Every estimate here had been
    "what will this cost" and never "what is left", which is how a four-model run
    got three 403s halfway through rather than a refusal up front.
    """
    # The SCHEDULER's reading first: it owns dispatch and therefore owns "how much
    # of today's pool is left". Reading its value rather than the provider's keeps
    # one number across every component instead of each computing its own.
    try:
        with urllib.request.urlopen(
            os.environ.get(
                "ANOMALICA_BUDGET_URL", "http://127.0.0.1:8001/api/budget/openrouter"
            ),
            timeout=5,
        ) as resp:
            d = json.loads(resp.read().decode()) or {}
        if d.get("ok") and d.get("budgetUsd") is not None:
            return float(d.get("usedUsd") or 0.0), float(d["budgetUsd"])
    except (OSError, ValueError):
        pass  # scheduler down: fall through to the provider

    key = os.environ.get("OPENROUTER_API_KEY")
    if not key:
        return None
    try:
        req = urllib.request.Request(
            "https://openrouter.ai/api/v1/key",
            headers={"Authorization": f"Bearer {key}"},
        )
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = (json.loads(resp.read().decode()) or {}).get("data") or {}
    except (OSError, ValueError):
        return None
    limit = data.get("limit")
    spent = data.get("usage_daily")
    if limit is None or spent is None:
        return None
    return float(spent), float(limit)


def estimate(args, kind: str, items: list[str]) -> tuple[list[str], list[str]]:
    """Print the spend estimate. Returns (resolved, unresolved) item lists."""
    # An OpenRouter model is a DIFFERENT cost shape, not just a different price:
    # its per-token rate comes from the shared table, its tokenizer is not the
    # one CHARS_PER_TOKEN was fitted to, and the large fixed term - the Claude
    # CLI's own system prompt - does not exist on that route at all. Using the
    # Claude constants here priced a metered Luna run at Sonnet's rate and
    # reported it as "no metered spend", which is the one thing this gate must
    # never say about a run that costs money.
    via_openrouter = asm.is_openrouter_model(args.model)
    if via_openrouter:
        from anomalica_common.llm.cost import price_for

        in_price, out_price = price_for(args.model)
        chars_per_token, fixed_in = 3.5, 0
    else:
        in_price, out_price = PRICING.get(args.model, PRICING["sonnet"])
        chars_per_token, fixed_in = CHARS_PER_TOKEN, FIXED_INPUT_TOKENS

    resolved: list[str] = []
    unresolved: list[str] = []
    total_in_tokens = 0
    for item in items:
        chars = _prompt_chars(args, kind, item)
        if chars is None:
            unresolved.append(item)
            continue
        resolved.append(item)
        total_in_tokens += fixed_in + round(chars / chars_per_token)

    per_item_out = EST_OUTPUT_TOKENS_RECORD if kind == "records" else EST_OUTPUT_TOKENS
    out_tokens = len(resolved) * per_item_out
    in_cost = total_in_tokens * in_price / 1_000_000
    out_cost = out_tokens * out_price / 1_000_000
    total = in_cost + out_cost
    on_api = asm._use_api() or via_openrouter

    print("=" * 60, file=sys.stderr)
    if on_api:
        provider = "OpenRouter" if via_openrouter else "Anthropic API"
        print(f"BATCH SPEND ESTIMATE (metered - {provider})", file=sys.stderr)
    else:
        print(
            "BATCH PRE-FLIGHT (Claude subscription - no metered spend, "
            "but spends plan allowance)",
            file=sys.stderr,
        )
    print(
        f"  {len(resolved)} {kind} x model={args.model} "
        f"(${in_price:.2f}/${out_price:.2f} per 1M in/out)",
        file=sys.stderr,
    )
    print(
        f"  input ~{total_in_tokens:,} tokens, output ~{out_tokens:,} tokens "
        f"(~{per_item_out}/item)",
        file=sys.stderr,
    )
    if on_api:
        print(
            f"  ESTIMATED METERED COST: ${total:,.2f}  (conservative; actual usually lower)",
            file=sys.stderr,
        )
    else:
        print(
            f"  Draws on the Max plan's finite weekly allowance - DISCOUNTED, "
            f"NOT FREE. Equivalent metered value ~${total:,.2f}. The allowance is "
            f"shared across every project and heavier models burn it fastest, so "
            f"this still needs clearing before it runs. (ASSEMBLER_USE_API=1 to "
            f"bill the metered API instead.)",
            file=sys.stderr,
        )
    if via_openrouter:
        budget = openrouter_budget_remaining()
        if budget is None:
            print(
                "  daily budget: UNREADABLE - proceeding blind, check before a "
                "large run",
                file=sys.stderr,
            )
        else:
            spent, limit = budget
            left = max(0.0, limit - spent)
            print(
                f"  shared daily budget: ${spent:,.2f} of ${limit:,.2f} used, "
                f"${left:,.2f} left (POOLED across every component on OpenRouter)",
                file=sys.stderr,
            )
            if total > left:
                print(
                    f"  *** THIS RUN ESTIMATES ${total:,.2f} AND ONLY ${left:,.2f} "
                    "REMAINS. It will 403 partway through, leaving some items "
                    "built and some not. Wait for the daily reset or cut the "
                    "list. ***",
                    file=sys.stderr,
                )
    if unresolved:
        print(
            f"  {len(unresolved)} unresolved (skipped): {', '.join(unresolved[:5])}"
            + (" ..." if len(unresolved) > 5 else ""),
            file=sys.stderr,
        )
    print("=" * 60, file=sys.stderr)
    return resolved, unresolved


def _run_one(cmd: list[str]) -> tuple[int, float | None]:
    """Run one assembler call. Returns (exit code, plan reset epoch or None).

    stderr is streamed rather than captured whole: an article can take minutes
    and a batch left running for days needs to show progress as it happens, not
    in a burst when each item exits. The plan-limit marker is picked out of that
    same stream on the way past.
    """
    reset: float | None = None
    proc = subprocess.Popen(
        cmd,
        cwd=str(Path(__file__).parent),
        stderr=subprocess.PIPE,
        text=True,
        bufsize=1,
    )
    for line in proc.stderr:
        sys.stderr.write(line)
        if line.startswith(asm._PLAN_LIMIT_MARKER):
            _, _, raw = line.partition("reset_at=")
            raw = raw.strip()
            if raw and raw != "-":
                try:
                    reset = float(raw)
                except ValueError:
                    reset = None
    proc.stderr.close()
    return proc.wait(), reset


def _wait_out_window(reset: float | None, blind_waits: int) -> float:
    """Seconds to sleep before retrying a throttled item.

    With a reported reset, sleep to it plus a small buffer - the plan reports the
    real number, so guessing an interval only wastes the window. Without one,
    back off 15/30/60 minutes and hold at 60: a throttled call is rejected before
    it generates anything, so re-probing is cheap, but probing every minute for
    a weekly cap is pointless noise.
    """
    if reset is not None:
        return max(60.0, reset - time.time() + 60.0)
    return [900.0, 1800.0, 3600.0][min(blind_waits, 2)]


def _hugo_smoke_test(site_root: str) -> bool:
    """Build the site once, so a page that breaks Hugo surfaces at the end of the
    batch instead of whenever someone next builds. Read-only: the build writes to
    site/public, never to content."""
    site = Path(site_root).expanduser()
    if not (site / "hugo.toml").is_file():
        print(f"\nHugo smoke test SKIPPED: no hugo.toml under {site}", file=sys.stderr)
        return True
    print(f"\n=== Hugo smoke test ({site}) ===", file=sys.stderr)
    proc = subprocess.run(["npm", "run", "build"], cwd=str(site))
    if proc.returncode == 0:
        print("Hugo smoke test PASSED", file=sys.stderr)
        return True
    print(
        f"Hugo smoke test FAILED (exit {proc.returncode}) - a page written by this "
        "batch breaks the site build. The articles are on disk; fix before merging.",
        file=sys.stderr,
    )
    return False


def generate(args, kind: str, items: list[str]) -> int:
    flag = {"nodes": "--node", "records": "--record", "briefs": "--brief"}[kind]
    common = [
        "--model",
        args.model,
        "--content-root",
        args.content_root,
    ]
    # Carry this batch's --confirm through to each child's own spend gate. The
    # children are separate processes, so the authorisation this driver took
    # from the operator does not otherwise reach them, and the metered backstop
    # in _call_api would refuse every item. No-op on the subscription path,
    # which is not metered and never consults it.
    # Any metered route, not just the Anthropic toggle: an OpenRouter model is
    # metered too, and its child gate would refuse every item without this.
    if (asm._use_api() or asm.is_openrouter_model(args.model)) and getattr(
        args, "confirm", False
    ):
        common.append("--confirm-spend")
    # The briefs root goes to every mode, not just --brief: it is also the
    # proposal set the body-link resolver indexes, and a record page links to
    # entities as heavily as an entity page does. Without it those links fall
    # back to whatever happens to be on disk at the time.
    common += ["--briefs-root", args.briefs_root, "--link-min-claims"]
    common += [str(args.link_min_claims)]
    # Forward the index cache so the children share one build. Rebuilding it costs
    # ~51s of yaml parsing, and a batch pays that PER PAGE without this - it was
    # the single largest term in wall-clock, larger than some generations.
    if args.link_index_cache:
        common += ["--link-index-cache", args.link_index_cache]
    # Record pages resolve their copyright status from the ingest store; without
    # this the gate fails closed and every record page would show no source.
    if args.ingests_root:
        common += ["--ingests-root", args.ingests_root]
    # The graph goes to every mode, not just --node: it is also where a page's
    # prior slugs live, and those become the redirect aliases. Without it a
    # rebuilt page silently loses its redirects, which is how two pages 404'd.
    common += ["--db", args.db]
    if kind == "briefs":
        # Briefs are the sole source, but the digests-root lets the assembler
        # carry forward each contributing record's ai_usage into the article.
        common += ["--digests-root", args.digests_root]
    else:
        common += ["--digests-root", args.digests_root]
    # One worker per lane. Each page is its own process for isolation, so the
    # pool just decides how many run at once; the per-item semantics below are
    # identical to the sequential path and --workers 1 reproduces it exactly.
    state = {
        "ok": 0,
        "failed": [],
        "consecutive_hard": 0,
        "throttled_waits": 0,
        "blind_waits": 0,
        "waited_total": 0.0,
        "abort": False,
        "done": 0,
    }
    lock = threading.Lock()
    max_wait = args.max_wait_hours * 3600.0
    total = len(items)

    def work(index: int, item: str) -> None:
        while True:
            with lock:
                if state["abort"]:
                    return
            print(f"\n=== [{index + 1}/{total}] {item} ===", file=sys.stderr)
            started = time.monotonic()
            code, reset = _run_one(
                # `--record=<item>`, not `--record <item>`: three digest names
                # begin with a hyphen, and argparse reads a bare one as a flag.
                # Cost one item of a five-item run to find; would have cost three
                # of the 77.
                [sys.executable, "assembler.py", f"{flag}={item}", *common]
            )
            elapsed = time.monotonic() - started
            # Wall-clock per page, always, not just on failure. A completion at
            # 870s against a 900s timeout is a different finding from one at
            # 240s, and pass/fail throws that distinction away - which is exactly
            # the signal needed to tell whether a brief is near its ceiling.
            print(
                f"  [{item}] {elapsed:.0f}s wall, exit {code}",
                file=sys.stderr,
            )

            if code == asm._EXIT_PLAN_RATE_LIMITED:
                # Not a failure: the window is full and the brief is untouched.
                with lock:
                    nap = _wait_out_window(reset, state["blind_waits"])
                    state["blind_waits"] = (
                        state["blind_waits"] + 1 if reset is None else 0
                    )
                    if state["waited_total"] + nap > max_wait:
                        print(
                            f"\nPlan throttled and the {args.max_wait_hours}h wait "
                            "budget is spent. Stopping.",
                            file=sys.stderr,
                        )
                        state["abort"] = True
                        return
                    state["waited_total"] += nap
                    state["throttled_waits"] += 1
                until = time.strftime("%H:%M %Z", time.localtime(time.time() + nap))
                print(
                    f"  plan window full - sleeping {nap / 60:.0f} min (until "
                    f"~{until}), then retrying this item. Not a failure.",
                    file=sys.stderr,
                )
                time.sleep(nap)
                continue  # same item, no strike

            with lock:
                state["done"] += 1
                if code == 0:
                    state["ok"] += 1
                    state["consecutive_hard"] = 0
                else:
                    state["failed"].append(item)
                    state["consecutive_hard"] += 1
                    if state["consecutive_hard"] >= args.max_consecutive_failures:
                        print(
                            f"\nABORTING: {state['consecutive_hard']} consecutive "
                            "failures (--max-consecutive-failures). Something is "
                            "broken beyond one bad brief.",
                            file=sys.stderr,
                        )
                        state["abort"] = True
            return

    workers = max(1, args.workers)
    if workers == 1:
        for i, item in enumerate(items):
            if i and args.delay:
                time.sleep(args.delay)
            work(i, item)
            if state["abort"]:
                break
    else:
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            futures = [pool.submit(work, i, item) for i, item in enumerate(items)]
            for f in futures:
                f.result()

    ok = state["ok"]
    failed = state["failed"]
    throttled_waits = state["throttled_waits"]
    waited_total = state["waited_total"]
    print(f"\nBatch: {ok} ok, {len(failed)} failed", file=sys.stderr)
    if throttled_waits:
        print(
            f"  paused {throttled_waits}x for the plan window "
            f"({waited_total / 3600:.1f}h total)",
            file=sys.stderr,
        )
    if failed:
        print("failed:", file=sys.stderr)
        for f in failed:
            print(f"  {f}", file=sys.stderr)
    site_root = args.site_root or str(
        Path(args.content_root).expanduser().resolve().parent / "site"
    )
    built = _hugo_smoke_test(site_root) if ok and not args.no_smoke_test else True
    return 0 if not failed and built else 1


def retarget_links(content_root: str, apply: bool, db_path: str | None = None) -> int:
    """Keep inspection_url only where the record page actually carries the claim.

    A record page is a SUMMARY - Mark's ruling - so it lists a fraction of the
    claims drawn from its source, while an entity page cites hundreds from the
    same record. The mismatch is permanent BY DESIGN and must not be closed by
    making record pages carry every claim; that would undo the summary shape.

    Measured before this ran: 3,294 claim links from entity pages into record
    pages, of which ~173 resolve. The rest land on the right page at the top,
    with the cited claim nowhere on it - worse than being sent somewhere that
    has it. So where the record page does not carry the claim, inspection_url is
    dropped and workbench_url (which renders the exact claim) becomes the link.

    A post-pass rather than a rule inside the writer, because a page cannot know
    which claims a record page will carry when that page is built later.
    Idempotent and re-runnable: as the missing record pages land, re-running
    UPGRADES links back from the workbench to the record page wherever one now
    carries the claim. Run it after every build.
    """
    root = Path(content_root).expanduser()
    pages = sorted(root.glob("pages/*/*.en.md"))

    # what each record page actually carries
    carries: dict[str, set[str]] = {}
    for md in root.glob("pages/records/*.en.md"):
        fm = _front_matter(md)
        carries[md.name[: -len(".en.md")]] = {
            str(r.get("claim_id"))
            for r in (fm.get("references") or [])
            if isinstance(r, dict) and r.get("claim_id")
        }

    # Claims that still exist. Re-ingestion re-mints claim ids, so a page built
    # before its source was re-digested cites ids the graph no longer holds -
    # 649 of 9,326 published references, 6%, across 22 pages. Those get NO link:
    # substituting the superseded record's new hash would open the right record
    # and highlight nothing, which is worse than a missing link because it looks
    # like it worked.
    live_claims: set[str] = set()
    # (record public hash, claim fingerprint) -> the claim's CURRENT id. The
    # fingerprint survives re-digestion where the id does not, so a citation that
    # would have been orphaned can instead be REPAIRED: same sentence, same
    # source, new id. Paired with the record hash because the fingerprint is
    # digest-local and the same sentence in two records would otherwise collide.
    by_fingerprint: dict[tuple[str, str], str] = {}
    if db_path and Path(db_path).is_file():
        try:
            conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
            live_claims = {str(r[0]) for r in conn.execute("SELECT id FROM claims")}
            for cid, content, ctype, excerpt, loc, chash in conn.execute(
                """SELECT c.id, c.content, c.claim_type, c.original_excerpt,
                          c.location_in_record, r.content_hash
                   FROM claims c JOIN records r ON r.id = c.record_id"""
            ):
                fp = asm._claim_fingerprint(
                    {
                        "content": content,
                        "claim_type": ctype,
                        "original_excerpt": excerpt,
                        "location_in_record": loc,
                    }
                )
                ph = asm._public_hash(chash)
                if fp and ph:
                    by_fingerprint[(ph, fp)] = str(cid)
            conn.close()
        except sqlite3.Error:
            live_claims = set()
            by_fingerprint = {}

    kept = dropped = restored = orphaned = repaired = 0
    changed_files = 0
    for md in pages:
        text = md.read_text(encoding="utf-8")
        m = re.match(r"^(---\n)(.*?)(\n---\n)(.*)$", text, re.S)
        if not m:
            continue
        try:
            fm = yaml.safe_load(m.group(2)) or {}
        except yaml.YAMLError:
            continue
        refs = fm.get("references")
        if not isinstance(refs, list):
            continue
        touched = False
        for r in refs:
            if not isinstance(r, dict):
                continue
            claim_id = str(r.get("claim_id") or "")
            # Before declaring a claim gone, try to re-find it by fingerprint: a
            # re-digest re-mints the id but not the sentence, so the citation is
            # repairable rather than dead.
            fp = str(r.get("claim_fingerprint") or "")
            ph = str(r.get("record_hash") or "")
            if live_claims and claim_id and claim_id not in live_claims and fp and ph:
                current = by_fingerprint.get((ph, fp))
                if current:
                    r["claim_id"] = current
                    r["workbench_url"] = f"{asm.WORKBENCH_ORIGIN}/{ph}#claim-{current}"
                    r.pop("inspection_url", None)
                    claim_id = current
                    repaired += 1
                    touched = True
            # A claim that no longer exists cannot be shown anywhere. Strip both
            # links and leave the reference text, which is still true.
            if live_claims and claim_id and claim_id not in live_claims:
                # Both pops must run: `a or b` short-circuits, so a reference
                # carrying BOTH links would keep the workbench one.
                had_inspection = r.pop("inspection_url", None) is not None
                had_workbench = r.pop("workbench_url", None) is not None
                if had_inspection or had_workbench:
                    orphaned += 1
                    touched = True
                continue
            slug = _inspection_slug(r.get("inspection_url"))
            resolves = bool(slug and claim_id and claim_id in carries.get(slug, set()))
            if r.get("inspection_url"):
                if resolves:
                    kept += 1
                else:
                    r.pop("inspection_url")
                    dropped += 1
                    touched = True
            elif claim_id:
                # A record page may have appeared since; upgrade back to it.
                for rec_slug, ids in carries.items():
                    if claim_id in ids:
                        r["inspection_url"] = f"/records/{rec_slug}#claim-{claim_id}"
                        restored += 1
                        touched = True
                        break
        if touched and apply:
            fm["references"] = refs
            md.write_text(
                "---\n"
                + yaml.safe_dump(fm, sort_keys=False, allow_unicode=True).strip()
                + "\n---\n"
                + m.group(4)
            )
        if touched:
            changed_files += 1

    verb = "rewritten" if apply else "would change"
    print("=" * 60, file=sys.stderr)
    print(f"INSPECTION-URL RETARGET ({verb})", file=sys.stderr)
    print(f"  kept      {kept:6,}  record page carries the claim", file=sys.stderr)
    print(
        f"  dropped   {dropped:6,}  it does not - workbench link stands alone",
        file=sys.stderr,
    )
    print(f"  restored  {restored:6,}  a record page now carries it", file=sys.stderr)
    print(
        f"  repaired  {repaired:6,}  id re-minted by a re-digest, re-found by fingerprint",
        file=sys.stderr,
    )
    print(
        f"  orphaned  {orphaned:6,}  claim no longer in the graph - no link",
        file=sys.stderr,
    )
    print(f"  files     {changed_files:6,}", file=sys.stderr)
    print("=" * 60, file=sys.stderr)
    if not apply:
        print("Dry run - pass --apply to write.", file=sys.stderr)
    return 0


def _brief_page_block(brief: Path) -> dict:
    """The `page:` mapping from a brief, read without parsing the whole file.

    A brief carries every claim behind its article and runs to thousands of
    lines, but the block naming the node sits in the first few. Parsing all 749
    in full costs a minute; stopping at the end of the block makes the check
    cheap enough to run on every batch, which is the only reason it gets run.
    """
    lines: list[str] = []
    try:
        with brief.open() as fh:
            for line in fh:
                if lines:
                    # a new top-level key ends the block
                    if line[:1] not in (" ", "\t", "\n", "#"):
                        break
                    lines.append(line)
                elif line.startswith("page:"):
                    lines.append(line)
    except OSError:
        return {}
    if not lines:
        return {}
    try:
        return (yaml.safe_load("".join(lines)) or {}).get("page") or {}
    except yaml.YAMLError:
        return {}


def _merge_survivor(conn, node_id: str) -> str | None:
    """The live node a retired one was merged into, or None.

    Follows the chain: 354 of the recorded merges name a survivor that has since
    been merged away itself, so the row against this node is often not the end of
    the trail. Reads node_merges rather than comparing names - a name heuristic
    scored "Roswell UAP Crash" closer to an unrelated 1948 crash sharing the
    words "UAP" and "crash" than to its actual survivor "Roswell incident
    (1947)", and a confidently wrong survivor is worse here than none: it invites
    pointing the redirect at the wrong article.
    """
    seen = {node_id}
    current = node_id
    while True:
        row = conn.execute(
            "SELECT m.survivor_id, n.retired_at FROM node_merges m "
            "JOIN nodes n ON n.id = m.survivor_id "
            "WHERE m.victim_id = ? AND m.undone_at IS NULL",
            (current,),
        ).fetchone()
        if row is None:
            return None
        survivor, retired = row
        if not retired:
            return survivor
        if survivor in seen:  # a cycle would otherwise spin here forever
            return None
        seen.add(survivor)
        current = survivor


def check_orphans(content_root: str, briefs_root: str, db_path: str) -> int:
    """Report published pages whose node has been retired from the graph.

    Nothing in the pipeline removes an artefact when its node retires, so a merge
    leaves the losing side's page and brief published and serving. The Roswell
    duplicate was caught by a human and the doubly-expanded AAV topic by an
    ad-hoc sweep; both were found by accident rather than by the system noticing.
    Run here because a check that runs on every batch beats a propagation step
    somebody has to remember, even though the root fix belongs upstream.

    Reports and never prunes. Removing the page is only safe once the URL
    redirects to the survivor, and this cannot know whether the site has that
    entry - pruning first would turn a wrong page into a silent 404.
    """
    root = Path(content_root).expanduser()
    briefs = Path(briefs_root).expanduser()
    if not briefs.is_dir():
        print(f"briefs dir not found: {briefs}", file=sys.stderr)
        return 2

    conn = sqlite3.connect(f"file:{Path(db_path).expanduser()}?mode=ro", uri=True)
    rows = conn.execute("SELECT id, node_type, name, retired_at FROM nodes").fetchall()
    by_id = {r[0]: r for r in rows}
    [r for r in rows if not r[3]]
    claims = dict(
        conn.execute("SELECT node_id, count(*) FROM claim_node_refs GROUP BY node_id")
    )

    stale: list[tuple] = []
    for brief in sorted(briefs.glob("*.yaml")):
        page = _brief_page_block(brief)
        if not page:
            continue
        node_id = page.get("node_id")
        row = by_id.get(node_id)
        if row is not None and not row[3]:
            continue  # node is live - nothing to say
        section = asm.SECTION_BY_TYPE.get(
            page.get("node_type"), f"{page.get('node_type')}s"
        )
        md = root / "pages" / section / f"{page.get('slug')}.en.md"
        if not md.is_file():
            continue  # brief alone is harmless; only a PUBLISHED page misleads

        survivor = None
        if row is not None:
            survivor = by_id.get(_merge_survivor(conn, node_id))
        stale.append((md, brief, row, claims.get(node_id, 0), survivor))

    if not stale:
        print(
            f"no stale pages: every published page maps to a live node ({len(rows)} nodes)"
        )
        return 0

    print(
        f"STALE PAGE: {len(stale)} published page(s) built from a node that is no "
        "longer live. Each is serving as though it were current.",
        file=sys.stderr,
    )
    for md, brief, row, held, survivor in stale:
        url = "/" + md.as_posix().split("pages/", 1)[1].replace(".en.md", "/")
        print(f"\n  {url}", file=sys.stderr)
        if row is None:
            print("      node   : GONE from the graph entirely", file=sys.stderr)
        else:
            print(
                f"      node   : {row[2][:64]!r}\n"
                f"      retired: {row[3]}   claims now: {held}",
                file=sys.stderr,
            )
        if survivor is not None:
            sec = asm.SECTION_BY_TYPE.get(survivor[1], f"{survivor[1]}s")
            spage = root / "pages" / sec / f"{asm.slugify(survivor[2])}.en.md"
            print(
                f"      survivor: {survivor[2][:56]!r} "
                f"({claims.get(survivor[0], 0)} claims, page "
                f"{'built' if spage.is_file() else 'NOT BUILT'})",
                file=sys.stderr,
            )
        else:
            print(
                "      survivor: none found - nothing to redirect to",
                file=sys.stderr,
            )
        print(f"      brief  : {brief}", file=sys.stderr)

    print(
        "\nNot pruned, deliberately. Get the redirect to the survivor in place at "
        "the site first, then remove the page and its brief - in that order. "
        "Removing the page first converts a wrong page into a silent 404.",
        file=sys.stderr,
    )
    return 1


def _front_matter(md: Path) -> dict:
    try:
        m = re.match(r"^---\n(.*?)\n---\n", md.read_text(encoding="utf-8"), re.S)
        return (yaml.safe_load(m.group(1)) or {}) if m else {}
    except (OSError, yaml.YAMLError):
        return {}


def _inspection_slug(url: object) -> str | None:
    if not isinstance(url, str) or not url.startswith("/records/"):
        return None
    return url[len("/records/") :].split("#", 1)[0] or None


def report_spend(content_root: str, since: str | None) -> int:
    """Report what assembly ACTUALLY cost, read back from the articles.

    The AI-operation ledger that ADR 0037 specifies has no table in either
    database, so the only surviving record of a run is the `built_by.tokens` block
    the assembler stamps into each article it writes. That made two unexplained
    runs recoverable after the fact - 6.3M tokens across 31 pages on 21 August -
    but only by hand-written queries at the time they were needed.

    This makes that recovery a command, so "what did that cost" is answerable by
    whoever asks rather than by whoever can write the query.
    """
    root = Path(content_root).expanduser()
    files = sorted(root.glob("pages/*/*.en.md"))
    if since:
        try:
            out = subprocess.run(
                ["git", "log", "--format=", "--name-only", f"{since}..HEAD"],
                cwd=str(root),
                capture_output=True,
                text=True,
                check=True,
            ).stdout.split()
        except (subprocess.CalledProcessError, OSError) as exc:
            print(f"cannot read git history in {root}: {exc}", file=sys.stderr)
            return 2
        touched = {n for n in out if n.endswith(".en.md")}
        # A run that was interrupted leaves its last pages uncommitted, and those
        # are precisely the ones somebody is asking about. Git history alone would
        # miss them - it missed 527k tokens across two pages when this was first
        # asked by hand.
        dirty = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=str(root),
            capture_output=True,
            text=True,
        ).stdout.splitlines()
        touched |= {
            line[3:].strip().strip('"')
            for line in dirty
            if line[3:].strip().strip('"').endswith(".en.md")
        }
        files = [f for f in files if str(f.relative_to(root)) in touched]

    rows, unstamped = [], []
    for f in files:
        tokens = asm.article_tokens(f)
        (rows.append((f, tokens)) if tokens else unstamped.append(f))

    tot_in = sum(t.get("input", 0) for _, t in rows)
    tot_out = sum(t.get("output", 0) for _, t in rows)
    scope = f"{since}..HEAD" if since else "all pages"
    print("=" * 60, file=sys.stderr)
    print(f"ASSEMBLY SPEND, READ BACK FROM THE ARTICLES ({scope})", file=sys.stderr)
    print(
        f"  {len(rows)} stamped article(s), {len(unstamped)} without a stamp",
        file=sys.stderr,
    )
    print(
        f"  input {tot_in:,} + output {tot_out:,} = {tot_in + tot_out:,} tokens",
        file=sys.stderr,
    )
    if unstamped:
        names = ", ".join(f.name for f in unstamped[:4])
        print(
            f"  unstamped (written before stamping, or by another tool): {names}"
            + (" ..." if len(unstamped) > 4 else ""),
            file=sys.stderr,
        )
    print("=" * 60, file=sys.stderr)
    for f, t in sorted(
        rows, key=lambda r: -(r[1].get("input", 0) + r[1].get("output", 0))
    )[:10]:
        n = t.get("input", 0) + t.get("output", 0)
        print(f"  {n:>10,}  {f.name}", file=sys.stderr)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--nodes", nargs="*", help="Node names/uuids to assemble")
    ap.add_argument("--records", nargs="*", help="Record digest names to assemble")
    ap.add_argument("--briefs", nargs="*", help="Brief page-slugs to assemble")
    ap.add_argument(
        "--nodes-file", help="File of node names, one per line (# comments ok)"
    )
    ap.add_argument("--records-file", help="File of record digest names, one per line")
    ap.add_argument("--briefs-file", help="File of brief page-slugs, one per line")
    ap.add_argument(
        "--db", default=asm.DEFAULT_DB, help="knowledge.db path (node mode)"
    )
    ap.add_argument(
        "--digests-root",
        default=asm.DEFAULT_DIGESTS_ROOT,
        help="digests repo (record mode; brief mode ai_usage carry-forward)",
    )
    ap.add_argument(
        "--briefs-root",
        default=asm.DEFAULT_BRIEFS_ROOT,
        help="briefs dir (brief mode)",
    )
    ap.add_argument("--content-root", default=asm.DEFAULT_CONTENT_ROOT)
    ap.add_argument("--model", default=asm.DEFAULT_MODEL, help="sonnet | opus | haiku")
    ap.add_argument(
        "--delay",
        type=float,
        default=0.0,
        help="Seconds to wait between calls, to pace a run against the shared "
        "subscription rate-limit (calls are sequential regardless).",
    )
    ap.add_argument(
        "--ingests-root",
        default="../ingests",
        help="ingests repo - where a record page's copyright status is read from",
    )
    ap.add_argument(
        "--link-index-cache",
        help="Share one body-link index across the run via this file (keyed on "
        "brief and page mtimes). Without it every page rebuilds it, ~51s each.",
    )
    ap.add_argument(
        "--workers",
        type=int,
        default=1,
        help="Pages to generate at once (default 1). Each is its own process, so "
        "this only sets how many lanes run; per-item behaviour is unchanged.",
    )
    ap.add_argument(
        "--retarget-links",
        action="store_true",
        help="Keep inspection_url only where the record page carries that claim; "
        "otherwise drop it so the workbench link stands. Idempotent - re-run "
        "after every build to upgrade links as record pages land.",
    )
    ap.add_argument(
        "--apply",
        action="store_true",
        help="With --retarget-links, write the changes (default is a dry run).",
    )
    ap.add_argument(
        "--check-orphans",
        action="store_true",
        help="Report published pages whose node has been retired from the graph "
        "(a merge leaves the losing side published), and exit. Reports only - "
        "the page cannot be pruned until its URL redirects to the survivor.",
    )
    ap.add_argument(
        "--report-spend",
        action="store_true",
        help="Report what assembly actually cost, summed from each article's "
        "built_by.tokens, and exit. The only surviving record of a run.",
    )
    ap.add_argument(
        "--since",
        help="With --report-spend, limit to pages changed since this git revision.",
    )
    ap.add_argument(
        "--allow-suspect-names",
        action="store_true",
        help="Assemble items whose name does not look like a real entity (a "
        "described speaker, or a person carrying an expanded acronym). Off by "
        "default: the resulting article reads as authoritative and is not.",
    )
    ap.add_argument(
        "--allow-slug-collisions",
        action="store_true",
        help="Proceed even when two items in the run write to the same file "
        "(last write wins). Off by default: the loss is otherwise invisible.",
    )
    ap.add_argument(
        "--link-min-claims",
        type=int,
        default=0,
        help="Claim floor below which a proposed page is not linkable. Set it to "
        "the floor this batch is assembling at, so articles do not link to pages "
        "the run will not write.",
    )
    ap.add_argument(
        "--max-consecutive-failures",
        type=int,
        default=5,
        help="Abort after this many consecutive HARD failures (default: 5). Plan "
        "throttling is not a failure and never counts towards this.",
    )
    ap.add_argument(
        "--max-wait-hours",
        type=float,
        default=24.0,
        help="Total time the batch may spend asleep waiting out plan windows "
        "before stopping with what it has (default: 24).",
    )
    ap.add_argument(
        "--site-root",
        help="Hugo site checked by the end-of-run smoke test (default: the "
        "'site' sibling of --content-root, which is how the repos are laid out)",
    )
    ap.add_argument(
        "--no-smoke-test",
        action="store_true",
        help="Skip the end-of-run Hugo build",
    )
    ap.add_argument(
        "--confirm",
        action="store_true",
        help="Spend money: generate the batch. Without this, only the estimate prints.",
    )
    args = ap.parse_args()

    if args.report_spend:
        return report_spend(args.content_root, args.since)

    if args.check_orphans:
        return check_orphans(args.content_root, args.briefs_root, args.db)

    if args.retarget_links:
        return retarget_links(args.content_root, args.apply, args.db)

    nodes = _read_items(args, "nodes")
    records = _read_items(args, "records")
    briefs = _read_items(args, "briefs")
    chosen = [
        (k, v)
        for k, v in (("nodes", nodes), ("records", records), ("briefs", briefs))
        if v
    ]
    if len(chosen) != 1:
        print(
            "provide exactly one of --nodes / --records / --briefs (or their -file form)",
            file=sys.stderr,
        )
        return 2
    kind, items = chosen[0]

    resolved, _ = estimate(args, kind, items)

    suspect = _check_suspect_names(args, kind, resolved)
    if suspect:
        print(
            f"\nSUSPECT ENTITY NAME: {len(suspect)} item(s) name something that "
            "does not look like a real entity. Assembling one publishes a confident, "
            "well-cited article about a subject that does not exist.",
            file=sys.stderr,
        )
        for item, why in suspect.items():
            print(f"  {item}\n      {why}", file=sys.stderr)
        if not args.allow_suspect_names:
            print(
                "\nRefusing to run. Fix the node in the graph, or drop these from the "
                "work list, or pass --allow-suspect-names to assemble them anyway.",
                file=sys.stderr,
            )
            return 2

    clashes = _check_slug_collisions(args, kind, resolved)
    if clashes:
        print(
            f"\nSLUG COLLISION: {len(clashes)} output path(s) claimed by more than "
            "one item in this run. Assembling both writes the same file twice and "
            "the second silently wins, so list order would decide the page.",
            file=sys.stderr,
        )
        for path, its in clashes.items():
            print(f"  {path}\n      <- {', '.join(its)}", file=sys.stderr)
        if not args.allow_slug_collisions:
            print(
                "\nRefusing to run. Merge the duplicate nodes, or drop all but one "
                "of each set from the work list, or pass --allow-slug-collisions to "
                "accept last-write-wins.",
                file=sys.stderr,
            )
            return 2

    if not args.confirm:
        tail = (
            "once the dollar amount above is cleared"
            if asm._use_api()
            else "to generate on the subscription"
        )
        print(
            f"\nPre-flight only - nothing generated. Re-run with --confirm {tail}.",
            file=sys.stderr,
        )
        return 0
    if not resolved:
        print("nothing resolved to generate", file=sys.stderr)
        return 2
    return generate(args, kind, resolved)


if __name__ == "__main__":
    sys.exit(main())
